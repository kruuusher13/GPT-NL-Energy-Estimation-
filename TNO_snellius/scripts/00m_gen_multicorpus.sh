#!/usr/bin/env bash
# Generate corpus-TAGGED per-(size, replicate) pipeline YAMLs for the
# multi-corpus shared-node sweep. Mirrors 00_gen_configs.sh exactly (same
# 4-stage template, same SLURM/EAR knobs from env.sh) but:
#   - slug is tagged with a corpus short-name  ->  run_{tag}_size{N}_rep{R}.yaml
#     so new shared-node runs NEVER clobber the exclusive calibration runs.
#   - each corpus gets its own DATA_DIR and its own size list.
#
# Usage:
#   source env.sh        # for PARTITION, TIME_*, NTASKS_*, MEM_*, RUNS_DIR, CONFIGS_DIR
#   bash 00m_gen_multicorpus.sh
#
# Edit the CORPORA / SIZES_* / REPS below to change the sweep.

set -euo pipefail
source "$(dirname "$0")/env.sh"
mkdir -p "$CONFIGS_DIR"

# ── Sweep definition ────────────────────────────────────────────────────────
DATASETS_ROOT="/projects/0/prjs0986/energy_studies/datasets"

# tag -> dataset dir.  *sh tags = SHARED-node runs (pipeline --exclusive removed).
declare -A CORPUS_DIR=(
  [amstsh]="$DATASETS_ROOT/american-stories"
  [euparlsh]="$DATASETS_ROOT/european_parliament"
)
# tag -> space-separated document-count limits (capped at 400k for the time budget)
declare -A CORPUS_SIZES=(
  [amstsh]="1000 100000 400000"
  [euparlsh]="100 1000"
)
REPS=2

gen_one() {
  local tag=$1 datadir=$2 size=$3 rep=$4
  local slug="${tag}_size${size}_rep${rep}"
  local out="$CONFIGS_DIR/run_${slug}.yaml"

  cat > "$out" <<YAML
# Auto-generated by 00m_gen_multicorpus.sh — do not edit by hand.
# Sweep: corpus=${tag}  data=${datadir}  size=${size}  replicate=${rep}  partition=${PARTITION}
# EAR:   enabled (hpc_ear: true)   |   shared-node (no --exclusive)

processing_type: hpc
input_from_previous_output: true

output_folder_template: "${RUNS_DIR}/${slug}/{pipeline_iteration}/stage{stage_idx}_{stage_name}"
logs_folder: "{output_folder}/logs"
slurm_logs_folder: "{output_folder}/slurm_logs"

mail_type: NONE
mail_user:

hpc_ear: "true"

stages:

  - stage: data_splitting
    input_folder: "${datadir}"
    hpc_partition: "${PARTITION}"
    hpc_time: "${TIME_DATA_SPLITTING}"
    hpc_n_tasks: "${NTASKS_DATA_SPLITTING}"
    hpc_mem_per_cpu_gb: "${MEM_PER_CPU}"
    ParquetReader:
      limit: "${size}"

  - stage: string_normalization
    hpc_partition: "${PARTITION}"
    hpc_time: "${TIME_STRING_NORM}"
    hpc_n_tasks: "${NTASKS_STRING_NORM}"
    hpc_mem_per_cpu_gb: "${MEM_PER_CPU}"
    FTFYFormatter:
      normalization: "NFC"

  - stage: heuristic_filtering
    hpc_partition: "${PARTITION}"
    hpc_time: "${TIME_HEURISTIC}"
    hpc_n_tasks: "${NTASKS_HEURISTIC}"
    hpc_mem_per_cpu_gb: "${MEM_PER_CPU}"
    LanguageFilter:
      languages: ["en", "nl", "da", "sv", "af", "fy", "de"]
      language_threshold: "0.65"
      backend: "ft176"
    NordicPileQualityFilter:
      max_digit_fraction: "0.2"
      min_n_char: "50"
      min_mean_med_char: "9"
      min_mean_med_word: "2.1"
    GopherQualityFilter:
      min_doc_words: "null"
      max_doc_words: "null"
      min_avg_word_length: "null"
      max_avg_word_length: "null"
      max_symbol_word_ratio: "0.1"
      max_bullet_lines_ratio: "0.9"
      max_ellipsis_lines_ratio: "0.3"
      max_non_alpha_words_ratio: "0.8"
      min_stop_words: "2"
    GopherRepetitionFilter:
      dup_line_frac: "0.35"
      dup_para_frac: "0.35"
      dup_line_char_frac: "0.2"
      dup_para_char_frac: "0.2"
      top_n_grams: [[2, 0.25], [3, 0.23], [4, 0.21]]
      dup_n_grams: [[5, 0.20], [6, 0.19], [7, 0.18], [8, 0.17], [9, 0.16], [10, 0.15]]

  - stage: deduplication
    hpc_partition: "${PARTITION}"
    hpc_time: "${TIME_DEDUP}"
    hpc_n_tasks: "${NTASKS_DEDUP}"
    hpc_mem_per_cpu_gb: "${MEM_PER_CPU_DEDUP}"
    MinhashConfig:
      num_buckets: 14
      hashes_per_bucket: 8
      n_grams: 5
YAML
  echo "  $out"
}

echo "[gen-mc] Writing tagged configs into $CONFIGS_DIR ..."
count=0
for tag in "${!CORPUS_DIR[@]}"; do
  datadir="${CORPUS_DIR[$tag]}"
  for size in ${CORPUS_SIZES[$tag]}; do
    for rep in $(seq 1 "$REPS"); do
      gen_one "$tag" "$datadir" "$size" "$rep"
      count=$((count + 1))
    done
  done
done
echo "[gen-mc] Generated $count tagged configs."
echo "[gen-mc] Submit only these with:  for f in \$CONFIGS_DIR/run_amst_*.yaml \$CONFIGS_DIR/run_euparl_*.yaml; do bash 01_submit_all.sh \"\$(basename \"\$f\" .yaml | sed 's/^run_//')\"; done"
