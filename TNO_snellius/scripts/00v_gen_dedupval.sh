#!/usr/bin/env bash
# Generate ONE validation config to confirm the dedup-EAR fix and produce dedup
# ground-truth energy for the EKF Mode-C validation. am-stories, size 100000, so
# stages 1-3 match the existing amst_size100000 measurements and stage 4 (dedup)
# finally yields an energy reading we never had.
#
# Usage:  source env.sh && bash 00v_gen_dedupval.sh && bash 01_submit_all.sh dedupval_size100000_rep1
set -euo pipefail
source "$(dirname "$0")/env.sh"
mkdir -p "$CONFIGS_DIR"

TAG="dedupval"
SIZE=100000
REP=1
DATADIR="/projects/0/prjs0986/energy_studies/datasets/american-stories"
slug="${TAG}_size${SIZE}_rep${REP}"
out="$CONFIGS_DIR/run_${slug}.yaml"

cat > "$out" <<YAML
# Auto-generated by 00v_gen_dedupval.sh — dedup-EAR fix validation run.
processing_type: hpc
input_from_previous_output: true

output_folder_template: "${RUNS_DIR}/${slug}/{pipeline_iteration}/stage{stage_idx}_{stage_name}"
logs_folder: "{output_folder}/logs"
slurm_logs_folder: "{output_folder}/slurm_logs"

mail_type: NONE
mail_user:

hpc_ear: "true"

stages:

  - stage: data_splitting
    input_folder: "${DATADIR}"
    hpc_partition: "${PARTITION}"
    hpc_time: "${TIME_DATA_SPLITTING}"
    hpc_n_tasks: "${NTASKS_DATA_SPLITTING}"
    hpc_mem_per_cpu_gb: "${MEM_PER_CPU}"
    ParquetReader:
      limit: "${SIZE}"

  - stage: string_normalization
    hpc_partition: "${PARTITION}"
    hpc_time: "${TIME_STRING_NORM}"
    hpc_n_tasks: "${NTASKS_STRING_NORM}"
    hpc_mem_per_cpu_gb: "${MEM_PER_CPU}"
    FTFYFormatter:
      normalization: "NFC"

  - stage: heuristic_filtering
    hpc_partition: "${PARTITION}"
    hpc_time: "${TIME_HEURISTIC}"
    hpc_n_tasks: "${NTASKS_HEURISTIC}"
    hpc_mem_per_cpu_gb: "${MEM_PER_CPU}"
    LanguageFilter:
      languages: ["en", "nl", "da", "sv", "af", "fy", "de"]
      language_threshold: "0.65"
      backend: "ft176"
    NordicPileQualityFilter:
      max_digit_fraction: "0.2"
      min_n_char: "50"
      min_mean_med_char: "9"
      min_mean_med_word: "2.1"
    GopherQualityFilter:
      min_doc_words: "null"
      max_doc_words: "null"
      min_avg_word_length: "null"
      max_avg_word_length: "null"
      max_symbol_word_ratio: "0.1"
      max_bullet_lines_ratio: "0.9"
      max_ellipsis_lines_ratio: "0.3"
      max_non_alpha_words_ratio: "0.8"
      min_stop_words: "2"
    GopherRepetitionFilter:
      dup_line_frac: "0.35"
      dup_para_frac: "0.35"
      dup_line_char_frac: "0.2"
      dup_para_char_frac: "0.2"
      top_n_grams: [[2, 0.25], [3, 0.23], [4, 0.21]]
      dup_n_grams: [[5, 0.20], [6, 0.19], [7, 0.18], [8, 0.17], [9, 0.16], [10, 0.15]]

  - stage: deduplication
    hpc_partition: "${PARTITION}"
    hpc_time: "${TIME_DEDUP}"
    hpc_n_tasks: "${NTASKS_DEDUP}"
    hpc_mem_per_cpu_gb: "${MEM_PER_CPU_DEDUP}"
    MinhashConfig:
      num_buckets: 14
      hashes_per_bucket: 8
      n_grams: 5
YAML
echo "[gen-v] wrote $out"
echo "[gen-v] submit with:  bash 01_submit_all.sh ${slug}"
