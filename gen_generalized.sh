#!/usr/bin/env bash
# Generalized sweep generator — adds the NTASKS axis + a GPU toxic-language run on
# top of the existing multi-corpus harness. Mirrors 00m_gen_multicorpus.sh's working
# 4-stage CPU template exactly, then parameterizes hpc_n_tasks across {1,16,32} and
# emits a SEPARATE, isolated split->toxic(H100) pipeline per (corpus,size).
#
#   tags:  amg_*  (american-stories) , epg_*  (european_parliament)   <- never clobber
#   slug:  {tag}_n{ntasks}_size{N}_rep{R}   (CPU sweep)
#          {tag}_toxic_size{N}              (GPU toxic, isolated)
#
# Usage (on Snellius):
#   cd /projects/0/prjs0986/energy_studies/test_romir/scripts
#   bash gen_generalized.sh
#   # then submit with 01_submit_all.sh per emitted slug (printed at the end)

set -euo pipefail
source "$(dirname "$0")/env.sh"
mkdir -p "$CONFIGS_DIR"

DATASETS_ROOT="/projects/0/prjs0986/energy_studies/datasets"
declare -A CORPUS_DIR=(
  [amg]="$DATASETS_ROOT/american-stories"
  [epg]="$DATASETS_ROOT/european_parliament"
  [ghub]="$DATASETS_ROOT/cc_github_opencode"
  [gerg]="$DATASETS_ROOT/cc_german-pd"
  [mix]="/projects/0/prjs0986/energy_studies/test_romir/datasets_mixed/mix4"
)
# Per-corpus sizes + memory, tuned to measured avg doc size (probe_corpora.py) so
# data_splitting never OOMs: am-stories ~1.8k chars, github ~3.1k, german ~49k,
# euro-parliament ~181k. Bigger docs -> smaller doc counts + more memory.
declare -A CORPUS_SIZES=(
  [amg]="100000 400000"
  [epg]="1000 10000"
  [ghub]="100000 400000"
  [gerg]="10000 100000"
  [mix]="50000"
)
declare -A CORPUS_MEM=(
  [amg]="1"
  [epg]="8"
  [ghub]="4"
  [gerg]="8"
  [mix]="8"
)
NTASKS_SWEEP=(1 16 32)
REPS=1

# ── CPU sweep: 4 stages on genoa, ntasks parameterized ──────────────────────────
gen_cpu() {
  local tag=$1 datadir=$2 size=$3 nt=$4 rep=$5 mem=$6
  local slug="${tag}_n${nt}_size${size}_rep${rep}"
  local out="$CONFIGS_DIR/run_${slug}.yaml"
  cat > "$out" <<YAML
# Auto-generated by gen_generalized.sh — CPU ntasks sweep. DO NOT hand-edit.
# corpus=${tag} data=${datadir} size=${size} ntasks=${nt} rep=${rep} partition=${PARTITION}
processing_type: hpc
input_from_previous_output: true
output_folder_template: "${RUNS_DIR}/${slug}/{pipeline_iteration}/stage{stage_idx}_{stage_name}"
logs_folder: "{output_folder}/logs"
slurm_logs_folder: "{output_folder}/slurm_logs"
mail_type: NONE
mail_user:
hpc_ear: "true"
stages:

  - stage: data_splitting
    input_folder: "${datadir}"
    hpc_partition: "${PARTITION}"
    hpc_time: "${TIME_DATA_SPLITTING}"
    hpc_n_tasks: "${nt}"
    hpc_mem_per_cpu_gb: "${mem}"
    ParquetReader:
      limit: "${size}"

  - stage: string_normalization
    hpc_partition: "${PARTITION}"
    hpc_time: "${TIME_STRING_NORM}"
    hpc_n_tasks: "${nt}"
    hpc_mem_per_cpu_gb: "${mem}"
    FTFYFormatter:
      normalization: "NFC"

  - stage: heuristic_filtering
    hpc_partition: "${PARTITION}"
    hpc_time: "${TIME_HEURISTIC}"
    hpc_n_tasks: "${nt}"
    hpc_mem_per_cpu_gb: "${mem}"
    LanguageFilter:
      languages: ["en", "nl", "da", "sv", "af", "fy", "de"]
      language_threshold: "0.65"
      backend: "ft176"
    NordicPileQualityFilter:
      max_digit_fraction: "0.2"
      min_n_char: "50"
      min_mean_med_char: "9"
      min_mean_med_word: "2.1"
    GopherQualityFilter:
      min_doc_words: "null"
      max_doc_words: "null"
      min_avg_word_length: "null"
      max_avg_word_length: "null"
      max_symbol_word_ratio: "0.1"
      max_bullet_lines_ratio: "0.9"
      max_ellipsis_lines_ratio: "0.3"
      max_non_alpha_words_ratio: "0.8"
      min_stop_words: "2"
    GopherRepetitionFilter:
      dup_line_frac: "0.35"
      dup_para_frac: "0.35"
      dup_line_char_frac: "0.2"
      dup_para_char_frac: "0.2"
      top_n_grams: [[2, 0.25], [3, 0.23], [4, 0.21]]
      dup_n_grams: [[5, 0.20], [6, 0.19], [7, 0.18], [8, 0.17], [9, 0.16], [10, 0.15]]

  - stage: deduplication
    hpc_partition: "${PARTITION}"
    hpc_time: "${TIME_DEDUP}"
    hpc_n_tasks: "${nt}"
    hpc_mem_per_cpu_gb: "${mem}"
    MinhashConfig:
      num_buckets: 14
      hashes_per_bucket: 8
      n_grams: 5
YAML
  echo "  CPU  $out"
}

# ── GPU toxic: isolated split(genoa)->toxic(gpu_h100) so it can't cascade ────────
gen_toxic() {
  local tag=$1 datadir=$2 size=$3 mem=$4
  local slug="${tag}_toxic_size${size}"
  local out="$CONFIGS_DIR/run_${slug}.yaml"
  cat > "$out" <<YAML
# Auto-generated by gen_generalized.sh — ISOLATED GPU toxic-language run. DO NOT hand-edit.
# corpus=${tag} data=${datadir} size=${size}  toxic on gpu_h100 (EAR GPU0_POWER_W captured)
processing_type: hpc
input_from_previous_output: true
output_folder_template: "${RUNS_DIR}/${slug}/{pipeline_iteration}/stage{stage_idx}_{stage_name}"
logs_folder: "{output_folder}/logs"
slurm_logs_folder: "{output_folder}/slurm_logs"
mail_type: NONE
mail_user:
hpc_ear: "true"
stages:

  - stage: data_splitting
    input_folder: "${datadir}"
    hpc_partition: "${PARTITION}"
    hpc_time: "01:00:00"
    hpc_n_tasks: "1"
    hpc_mem_per_cpu_gb: "${mem}"
    ParquetReader:
      limit: "${size}"

  - stage: toxic_language_detection
    hpc_partition: "gpu_h100"
    hpc_time: "02:00:00"
    hpc_n_tasks: "1"
    hpc_gpus: "1"
    hpc_mem_per_cpu_gb: "4"
    ToxicLanguageDetection:
      threshold: "0.995"
      max_chunk_length: "256"
YAML
  echo "  GPU  $out"
}

echo "[gen-gen] Writing generalized configs into $CONFIGS_DIR ..."
cpu=0; gpu=0
for tag in "${!CORPUS_DIR[@]}"; do
  datadir="${CORPUS_DIR[$tag]}"
  mem="${CORPUS_MEM[$tag]}"
  for size in ${CORPUS_SIZES[$tag]}; do
    for nt in "${NTASKS_SWEEP[@]}"; do
      for rep in $(seq 1 "$REPS"); do
        gen_cpu "$tag" "$datadir" "$size" "$nt" "$rep" "$mem"; cpu=$((cpu+1))
      done
    done
    gen_toxic "$tag" "$datadir" "$size" "$mem"; gpu=$((gpu+1))
  done
done
echo "[gen-gen] Generated $cpu CPU-sweep + $gpu GPU-toxic configs."
echo "[gen-gen] CPU slugs:"; ls "$CONFIGS_DIR"/run_*_n*_size*.yaml 2>/dev/null | sed 's/.*run_//;s/.yaml//' | sed 's/^/    /'
echo "[gen-gen] GPU slugs:"; ls "$CONFIGS_DIR"/run_*_toxic_*.yaml 2>/dev/null | sed 's/.*run_//;s/.yaml//' | sed 's/^/    /'
